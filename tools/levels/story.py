def level_lines(world, n, level_id):
    """(intro, outro) of a level as dialogue lines with voice ids."""
    pre = "l%02d" % level_id
    intro, outro = [], []
    if n == 1:
        intro = [("pilo", "کلید زمان این مرحله را پیدا کنیم!")]
    elif n == 7:
        intro = [("pilo", "راه مخفی؛ پر از گنج! الماس افسانه‌ای این جهان همین‌جاست.")]
        outro = [("nima", "الماس افسانه‌ای! یکی دیگر تا سرزمین وارونه.")]
    elif n == 8:
        who, freed_line, companion, join = GUARDIAN[world]
        names = {"bear": "خرس پیر جنگل", "octopus": "اختاپوس بزرگ", "worm": "کرم شنی", "yeti": "غول یخی",
                 "eagle": "عقاب طوفان", "spider": "عنکبوت بلورین", "grandpa": "ساعت‌ساز طلسم‌شده",
                 "shadow_king": "شاه‌سایه", "zurvan": "زروان"}
        intro = [("pilo", "%s! طلسم سایه او را عصبانی کرده. روی سرش بپر، تیر بزن یا مرا بفرست تا آزاد شود!" % names[who])]
        outro = [(who, freed_line)]
        if companion:
            outro.append((companion, join))
            outro.append(("pilo", "از حالا در دهکده یا با دکمهٔ همراه، می‌توانی او را انتخاب کنی."))
    else:
        intro = LEVELS.get(world, {}).get(n, [("pilo", "کلید زمان را پیدا کنیم!")])
    to = lambda lines, kind: [{"who": w, "text": t, "id": "%s_%s_%d" % (pre, kind, i + 1)} for i, (w, t) in enumerate(lines)]
    return to(intro, "intro"), to(outro, "outro")


RACES = {("coral_beach", 2), ("snow_mountain", 2), ("crystal_caves", 2)}


def main():
    out = {w: {"title": c["title"], "lines": [{"who": who, "text": t, "id": "ch_%s_%d" % (w, i + 1)} for i, (who, t) in enumerate(c["lines"])]}
           for w, c in CHAPTERS.items()}
    path = os.path.join(ROOT, "data", "story", "chapters.json")
    json.dump(out, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
